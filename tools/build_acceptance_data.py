TEMPLATE = REPO_ROOT / "src" / "workbook" / "FRTB_Template.xlsx"
MODULE = REPO_ROOT / "tests" / "modules" / "TEST_AcceptanceData.bas"
SUMMARY_ITEMS = ("SBM_LOW", "SBM_MEDIUM", "SBM_HIGH", "SBM", "DRC_NONSEC", "RRAO", "TOTAL")

UPDATED = "2026-11-22"  # the date of the last change to the layout of the module
RULE = "'" + "-" * 78
EQUALS = "'" + "=" * 78


def _fields(pairs: list[tuple[str, list[str]]]) -> list[str]:
    """The documentation fields of the house style, UPDATED last."""
    lines: list[str] = []
    for label, text in [*pairs, ("UPDATED", [UPDATED])]:
        lines.append("' " + label)
        lines += ["'   " + line if line else "'" for line in text]
        lines.append("'")
    return lines[:-1]


