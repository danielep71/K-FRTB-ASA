def _procedure(
    name: str, title: str, kind: str, purpose: str, returns: str, items: list[str], collection: bool
) -> list[str]:
    """One generated function with its banner, documentation block and sections."""
    centered = "'" + " " * ((78 - len(title)) // 2) + title
    lines = [f"Public Function {name}() As {kind}", "", "'", RULE, centered, RULE]
    lines += _fields([
        ("PURPOSE", [purpose]),
        ("WHY THIS EXISTS", ["The Excel check compares the workbook with this data, which the reference computes."]),
        ("INPUTS", ["None"]),
        ("RETURNS", [returns]),
        ("BEHAVIOR", ["Builds the data from literals written by the generator."]),
        ("ERROR POLICY", ["None"]),
        ("DEPENDENCIES", ["None"]),
        ("NOTES", ["Generated: do not edit by hand."]),
    ])
    lines += [RULE, ""]
    if collection:
        lines += [RULE, "' DECLARE", RULE, f'    Const PROC_NAME             As String = "TEST_AcceptanceData.{name}"', "",
                  "    Dim Items                   As New Collection   'The data, one Array or text per entry", "",
                  RULE, "' BUILD THE DATA", RULE, "    'Add one entry per row of data"]
        lines += ["        " + item for item in items]
        lines += ["", RULE, "' RETURN VALUE", RULE, "    'Return the collection", f"        Set {name} = Items"]
    else:
        lines += [RULE, "' RETURN VALUE", RULE, "    'Return the data"]
        lines += ["        " + item for item in items]
    lines += ["", "End Function"]
    return lines


def vba_literal(value: Any) -> str:
    """Return the VBA literal of a cell value."""
    if value is None:
        return "Empty"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        # As tools/update_expected.py writes them: six decimals at most and no
        # ".0", the form the VBA editor keeps, so the source round trip of the
        # Excel run compares equal (#30)
        if not math.isfinite(value):
            raise ValueError(f"not a finite number: {value!r}")
        text = repr(round(value, 6))
        return text[:-2] if text.endswith(".0") else text
    if isinstance(value, str):
        return '"' + value.replace('"', '""') + '"'
    raise TypeError(f"no VBA literal for {type(value).__name__}: {value!r}")


def reference_summary(variant: bool) -> Mapping[str, Any]:
    wb = openpyxl.load_workbook(TEMPLATE)
    if variant:
        cases.apply_variant(wb)
    result: Mapping[str, Any] = ref.run(ref.params_from_workbook(wb), ref.inputs_from_workbook(wb))["summary"]
    return result


def expected_items(summary: Mapping[str, Any]) -> list[str]:
    items = [f'Items.Add Array("{item}", {vba_literal(float(summary[item]))})' for item in SUMMARY_ITEMS]
    items.append(f'Items.Add Array("SBM_SCENARIO", {vba_literal(str(summary["SBM_SCENARIO"]))})')
    return items


def presentation_items() -> tuple[list[str], list[str]]:
    """Return the frozen panes and autofilters of the committed template."""
    wb = openpyxl.load_workbook(TEMPLATE)
    panes: list[str] = []
    filters: list[str] = []
    for ws in wb.worksheets:
        pane = ws.sheet_view.pane
        if pane is not None and pane.state == "frozen":
            rows, columns = int(pane.ySplit or 0), int(pane.xSplit or 0)
            panes.append(f"Items.Add Array({vba_literal(ws.title)}, {rows}, {columns})")
        if ws.auto_filter.ref:
            filters.append(f"Items.Add Array({vba_literal(ws.title)}, {vba_literal(ws.auto_filter.ref)})")
    return panes, filters


def _constants() -> list[str]:
    rows = [
        ("ACCEPTANCE_VARIANT_ERRORS", cases.EXPECTED_ERRORS, "Errors the Log shows after the variant run"),
        ("ACCEPTANCE_VARIANT_WARNINGS", cases.EXPECTED_WARNINGS, "Warnings the Log shows after the variant run"),
    ]
    left = [f"Public Const {name}" for name, _, _ in rows]
    width = -(-(max(len(item) for item in left) + 1) // 4) * 4
    mid = [f"As Long = {value}" for _, value, _ in rows]
    mid_width = -(-(max(len(item) for item in mid) + 1) // 4) * 4
    return ["    " + item.ljust(width) + m.ljust(mid_width) + "'" + note for item, m, (_, _, note) in zip(left, mid, rows)]


def validation_lines() -> list[str]:
    """Return the data validation rules of the committed template: Excel's type
    (3 list, 7 custom) and alert style (1 stop, 2 warning) with each rule's title."""
    lines: list[str] = []
    for rule in input_validation.read_rules(TEMPLATE):
        kind = 7 if rule.kind == "custom" else 3
        alert = 2 if rule.alert == "warning" else 1
        first = rule.sqref.split(":")[0]
        lines.append(
            f"Items.Add Array({vba_literal(rule.sheet)}, {vba_literal(first)}, {kind}, {alert}, {vba_literal(rule.title)})"
        )
    return lines


def key_table_lines() -> list[str]:
    """Return the Key | Value tables whose repeated keys are highlighted: sheet, first and last data row."""
    lines: list[str] = []
    for highlight in key_highlights.expected_highlights(TEMPLATE):
        first, last = (int(part[1:]) for part in highlight.sqref.split(":"))
        lines.append(f"Items.Add Array({vba_literal(highlight.sheet)}, {first}, {last})")
    return lines


def render() -> str:
    panes, filters = presentation_items()
    rows: list[str] = []
    for sheet, sheet_rows in cases.INVALID_ROWS.items():
        for values in sheet_rows:
            rows.append(f"Items.Add Array({vba_literal(sheet)}, 0, " + ", ".join(vba_literal(v) for v in values) + ")")
        if sheet == "In_Curvature":
            rows.append(
                f"Items.Add Array({vba_literal(sheet)}, {cases.BOOLEAN_COLUMN}, "
                + ", ".join(vba_literal(v) for v in cases.BOOLEAN_ROW)
                + ")"
            )
    sub_type_rows = [
        f"Items.Add Array({vba_literal(sheet)}, 0, " + ", ".join(vba_literal(v) for v in values) + ")"
        for sheet, sheet_rows in cases.UNDEFINED_SUB_TYPE_ROWS.items()
        for values in sheet_rows
    ]
    sub_type_errors = [f"Items.Add {vba_literal(message)}" for message in cases.UNDEFINED_SUB_TYPE_ERRORS]
    procedures = [
        _procedure("AcceptanceDiscretions", "RETURN THE DISCRETIONS", "Variant", "Returns the Control settings that the variant switches on.",
                   "An array of setting codes.",
                   ["AcceptanceDiscretions = Array(" + ", ".join(vba_literal(d) for d in cases.DISCRETIONS) + ")"], False),
        _procedure("AcceptanceBooleanFormat", "RETURN THE BOOLEAN FORMAT", "String", "Returns the number format given to the Boolean cell of the variant.",
                   "The number format.", [f"AcceptanceBooleanFormat = {vba_literal(cases.BOOLEAN_FORMAT)}"], False),
        _procedure("AcceptanceRows", "RETURN THE INVALID ROWS", "Collection", "Returns the rows of the invalid-row variant.",
                   "One Array per row: sheet, column to give the Boolean format (0 for none), then the cell values from column C.",
                   rows, True),
        _procedure("AcceptanceSubTypeRows", "RETURN THE SUB-TYPE ROWS", "Collection", "Returns the rows with sub-types that MAR21 does not define.",
                   "One Array per row, in the form of AcceptanceRows.", sub_type_rows, True),
        _procedure("AcceptanceSubTypeErrors", "RETURN THE SUB-TYPE ERRORS", "Collection", "Returns the Log messages that the undefined sub-type rows must produce.",
                   "The expected messages, sorted.", sub_type_errors, True),
        _procedure("AcceptanceSampleExpected", "RETURN THE SAMPLE RESULTS", "Collection", "Returns the Out_Summary items of the sample portfolio and their reference values.",
                   "Array(item, value) pairs.", expected_items(reference_summary(variant=False)), True),
        _procedure("AcceptanceVariantExpected", "RETURN THE VARIANT RESULTS", "Collection", "Returns the Out_Summary items of the variant and their reference values.",
                   "Array(item, value) pairs.", expected_items(reference_summary(variant=True)), True),
        _procedure("AcceptancePanes", "RETURN THE FROZEN PANES", "Collection", "Returns the frozen panes of the committed template.",
                   "Array(sheet, frozen rows, frozen columns) for every sheet the template freezes.", panes, True),
        _procedure("AcceptanceFilters", "RETURN THE AUTOFILTERS", "Collection", "Returns the autofilters of the committed template.",
                   "Array(sheet, autofilter range) for every sheet the template filters.", filters, True),
        _procedure("AcceptanceValidation", "RETURN THE VALIDATION RULES", "Collection", "Returns the data validation rules of the committed template.",
                   "Array(sheet, first cell, type, alert style, error title) for every rule.", validation_lines(), True),
        _procedure("AcceptanceKeyTables", "RETURN THE KEY TABLES", "Collection", "Returns the Key | Value tables whose repeated keys are highlighted.",
                   "Array(sheet, first row, last row) for every table.", key_table_lines(), True),
    ]
    lines = [HEADER, "", RULE, "' PUBLIC CONSTANTS", RULE, *_constants(), "", "", "'", RULE, "'",
             "'" + " " * ((78 - len("PUBLIC DATA")) // 2) + "PUBLIC DATA", "'", RULE, "'", ""]
    for index, procedure in enumerate(procedures):
        if index:
            lines.append("")
        lines += procedure
    return "\r\n".join(lines).replace("\r\n", "\n").replace("\n", "\r\n") + "\r\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is stale")
    args = parser.parse_args(argv)
    text = render()
    current = MODULE.read_bytes().decode("cp1252") if MODULE.exists() else None
    if args.check:
        if current != text:
            print(f"{MODULE.relative_to(REPO_ROOT)} is stale: run python3 tools/build_acceptance_data.py")
            return 1
        print(f"{MODULE.relative_to(REPO_ROOT)} is current")
        return 0
    if current != text:
        MODULE.write_bytes(text.encode("cp1252"))
        print(f"wrote {MODULE.relative_to(REPO_ROOT)}")
    else:
        print(f"{MODULE.relative_to(REPO_ROOT)} is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
