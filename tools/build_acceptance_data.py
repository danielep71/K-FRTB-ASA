"""Write the data of the unattended Excel checks into TEST_AcceptanceData.bas.

The module holds the invalid-row variant of tests/acceptance_cases.py, the
results that the independent reference, tests/frtb_reference.py, computes for
the sample portfolio and for that variant, and the frozen panes and
autofilters of the committed template src/workbook/FRTB_Template.xlsx. The
reference reads that template, so the expected values never come from the VBA
under test (#274).

Usage:
    python3 tools/build_acceptance_data.py          # rewrite the module
    python3 tools/build_acceptance_data.py --check  # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import math
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import openpyxl

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "tests"))

import acceptance_cases as cases  # noqa: E402
import frtb_reference as ref  # noqa: E402

TEMPLATE = REPO_ROOT / "src" / "workbook" / "FRTB_Template.xlsx"
MODULE = REPO_ROOT / "tests" / "modules" / "TEST_AcceptanceData.bas"
SUMMARY_ITEMS = ("SBM_LOW", "SBM_MEDIUM", "SBM_HIGH", "SBM", "DRC_NONSEC", "RRAO", "TOTAL")

HEADER = """\
Attribute VB_Name = "TEST_AcceptanceData"
'==============================================================================
' MODULE: TEST_AcceptanceData
'------------------------------------------------------------------------------
' PURPOSE
'   The data of the unattended Excel checks (TEST_Acceptance): the rows of
'   the invalid-row variant, the results of the independent reference for
'   the sample portfolio and for that variant, and the frozen panes and
'   autofilters of the committed template.
'
'   GENERATED by tools/build_acceptance_data.py from tests/acceptance_cases.py
'   and tests/frtb_reference.py; do not edit by hand.
'
' PUBLIC SURFACE
'   AcceptanceDiscretions: the Control settings the variant switches on.
'   AcceptanceRows: one Array per row: sheet, column to give the Boolean
'     format (0 for none), then the cell values from column C.
'   AcceptanceBooleanFormat: that number format.
'   AcceptanceSampleExpected, AcceptanceVariantExpected: Out_Summary items
'     and their reference values, as Array(item, value) pairs.
'   ACCEPTANCE_VARIANT_ERRORS, ACCEPTANCE_VARIANT_WARNINGS: the Log counts
'     of the variant run.
'   AcceptancePanes: Array(sheet, frozen rows, frozen columns) for every
'     sheet the template freezes.
'   AcceptanceFilters: Array(sheet, autofilter range) for every sheet the
'     template filters.
'
' DEPENDENCIES
'   None.
'
' STATE OWNERSHIP
'   None.
'
' ERROR POLICY
'   None: data only.
'
' COMPATIBILITY
'   Excel VBA; also runs in LibreOffice Calc with VBA support for the
'   automated tests. Development build only: tools/Build-Workbook.ps1
'   -Production leaves this module out.
'==============================================================================

'------------------------------------------------------------------------------
'                              MODULE SETTINGS
'------------------------------------------------------------------------------
Option Explicit
"""


def vba_literal(value: Any) -> str:
    """Return the VBA literal of a cell value."""
    if value is None:
        return "Empty"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        # As tools/update_expected.py writes them: six decimals at most and no
        # ".0", the form the VBA editor keeps, so the source round trip of the
        # Excel run compares equal (#30)
        if not math.isfinite(value):
            raise ValueError(f"not a finite number: {value!r}")
        text = repr(round(value, 6))
        return text[:-2] if text.endswith(".0") else text
    if isinstance(value, str):
        return '"' + value.replace('"', '""') + '"'
    raise TypeError(f"no VBA literal for {type(value).__name__}: {value!r}")


def reference_summary(variant: bool) -> Mapping[str, Any]:
    wb = openpyxl.load_workbook(TEMPLATE)
    if variant:
        cases.apply_variant(wb)
    result: Mapping[str, Any] = ref.run(ref.params_from_workbook(wb), ref.inputs_from_workbook(wb))["summary"]
    return result


def expected_function(name: str, summary: Mapping[str, Any]) -> list[str]:
    lines = [f"Public Function {name}() As Collection", "    Dim c As New Collection"]
    for item in SUMMARY_ITEMS:
        lines.append(f'    c.Add Array("{item}", {vba_literal(float(summary[item]))})')
    lines.append(f'    c.Add Array("SBM_SCENARIO", {vba_literal(str(summary["SBM_SCENARIO"]))})')
    lines += [f"    Set {name} = c", "End Function"]
    return lines


def presentation_lines() -> list[str]:
    """Return the frozen panes and autofilters of the committed template."""
    wb = openpyxl.load_workbook(TEMPLATE)
    panes = ["Public Function AcceptancePanes() As Collection", "    Dim c As New Collection"]
    filters = ["Public Function AcceptanceFilters() As Collection", "    Dim c As New Collection"]
    for ws in wb.worksheets:
        pane = ws.sheet_view.pane
        if pane is not None and pane.state == "frozen":
            rows, columns = int(pane.ySplit or 0), int(pane.xSplit or 0)
            panes.append(f"    c.Add Array({vba_literal(ws.title)}, {rows}, {columns})")
        if ws.auto_filter.ref:
            filters.append(f"    c.Add Array({vba_literal(ws.title)}, {vba_literal(ws.auto_filter.ref)})")
    panes += ["    Set AcceptancePanes = c", "End Function"]
    filters += ["    Set AcceptanceFilters = c", "End Function"]
    return panes + ["", ""] + filters


def render() -> str:
    lines = [HEADER.rstrip("\n"), ""]
    lines += [
        "'------------------------------------------------------------------------------",
        "'                              PUBLIC CONSTANTS",
        "'------------------------------------------------------------------------------",
        f"Public Const ACCEPTANCE_VARIANT_ERRORS As Long = {cases.EXPECTED_ERRORS}",
        f"Public Const ACCEPTANCE_VARIANT_WARNINGS As Long = {cases.EXPECTED_WARNINGS}",
        "",
        "'------------------------------------------------------------------------------",
        "'                               PUBLIC DATA",
        "'------------------------------------------------------------------------------",
        "Public Function AcceptanceDiscretions() As Variant",
        "    AcceptanceDiscretions = Array(" + ", ".join(vba_literal(d) for d in cases.DISCRETIONS) + ")",
        "End Function",
        "",
        "",
        "Public Function AcceptanceBooleanFormat() As String",
        f"    AcceptanceBooleanFormat = {vba_literal(cases.BOOLEAN_FORMAT)}",
        "End Function",
        "",
        "",
        "Public Function AcceptanceRows() As Collection",
        "    Dim c As New Collection",
    ]
    for sheet, rows in cases.INVALID_ROWS.items():
        for values in rows:
            lines.append(f"    c.Add Array({vba_literal(sheet)}, 0, " + ", ".join(vba_literal(v) for v in values) + ")")
        if sheet == "In_Curvature":
            lines.append(
                f"    c.Add Array({vba_literal(sheet)}, {cases.BOOLEAN_COLUMN}, "
                + ", ".join(vba_literal(v) for v in cases.BOOLEAN_ROW)
                + ")"
            )
    lines += ["    Set AcceptanceRows = c", "End Function", "", ""]
    lines += expected_function("AcceptanceSampleExpected", reference_summary(variant=False))
    lines += ["", ""]
    lines += expected_function("AcceptanceVariantExpected", reference_summary(variant=True))
    lines += ["", ""] + presentation_lines()
    return "\r\n".join("\n".join(lines).split("\n")) + "\r\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is stale")
    args = parser.parse_args(argv)
    text = render()
    current = MODULE.read_bytes().decode("cp1252") if MODULE.exists() else None
    if args.check:
        if current != text:
            print(f"{MODULE.relative_to(REPO_ROOT)} is stale: run python3 tools/build_acceptance_data.py")
            return 1
        print(f"{MODULE.relative_to(REPO_ROOT)} is current")
        return 0
    if current != text:
        MODULE.write_bytes(text.encode("cp1252"))
        print(f"wrote {MODULE.relative_to(REPO_ROOT)}")
    else:
        print(f"{MODULE.relative_to(REPO_ROOT)} is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
